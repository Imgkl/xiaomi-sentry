import SwiftUI

/// Text drawn as a 5x7 dot-matrix display.
struct DotMatrixText: View {
    let text: String
    var dot: CGFloat = 1.7
    var gap: CGFloat = 0.55
    var color: Color = .white

    var body: some View {
        let chars = Array(text.uppercased())
        let cell = dot + gap
        let width = max(CGFloat(chars.count) * 6 * cell - cell - gap, 1)
        Canvas { context, _ in
            for (i, ch) in chars.enumerated() {
                guard let rows = DotFont.glyphs[ch] else { continue }
                for (row, bits) in rows.enumerated() {
                    for col in 0..<5 where bits & (1 << (4 - col)) != 0 {
                        let rect = CGRect(x: CGFloat(i * 6 + col) * cell, y: CGFloat(row) * cell, width: dot, height: dot)
                        context.fill(Path(ellipseIn: rect), with: .color(color))
                    }
                }
            }
        }
        .frame(width: width, height: 7 * cell - gap)
        .accessibilityLabel(text)
    }
}

